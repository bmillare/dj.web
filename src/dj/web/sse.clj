(defn write-event!
  "Append one SSE event to `appendable` (a StringBuilder, a BufferedWriter, ...)
  and return it. Same signature as `starfederation.datastar.clojure.api.sse/
  write-event!`, and byte-identical to it — `sse-test` asserts that over the
  full option matrix.

  The frame, in exactly this order:

    1. `event: <event-type>\\n`      always
    2. `id: <id>\\n`                 only when `id` is truthy
    3. `retry: <n>\\n`               only when `retry-duration` is truthy
    4. `data: <line>\\n`             once per data line
    5. `\\n`                         the blank line that ends the event

  \"Truthy\", not \"present\": `normalize-event-opts` returns a map that always
  has both keys and sets a dropped one to **`false`** — so that is the shape of
  the *default* call, and a `contains?`/`some?` test here would put `id: false`
  on the wire for every ordinary event.

  Unlike the SDK we do NOT wrap append failures in `ex-info`. The SDK's wrapping
  costs more than it explains: the only thing that realistically throws here is
  the socket, and an `IOException` wrapped in an `ex-info` no longer satisfies
  the `(instance? IOException e)` test in `ac/default-on-exception`, so a
  disconnected client would be rethrown as an error instead of quietly closing
  the generator. (Latent in the SDK rather than live: with the temp-buffer write
  profiles the appends land in a StringBuilder and the socket is only touched
  afterwards — it bites the buffered-writer profiles, which write through.)"
  ^Appendable [^Appendable appendable event-type data-lines opts]
  (let [event-id (get opts id)
        retry    (get opts retry-duration)]
    (doto appendable
      (.append "event: ")
      (.append (str event-type))
      (.append "\n"))
    (when event-id
      (doto appendable
        (.append "id: ")
        (.append (str event-id))
        (.append "\n")))
    (when retry
      (doto appendable
        (.append "retry: ")
        (.append (str retry))
        (.append "\n")))
    (doseq [line data-lines]
      (doto appendable
        (.append "data: ")
        (.append (str line))
        (.append "\n")))
    (.append appendable "\n")
    appendable))

(defn write-comment!
  "Append an SSE comment frame — `: <text>` and the blank line — and return
  `appendable`. A comment is a no-op for the client: it is not an event, fires
  no listener, and patches nothing. It exists to put bytes on an idle socket so
  a dead peer is discovered by a failed write rather than by silence.

  **This is the capability that owning layer 3 buys**, and the reason that slice
  went first. The SDK structurally cannot emit one: every path into a generator
  goes through `p/send-event!`, which writes `event: <type>` before anything
  else. A heartbeat through the SDK is therefore a no-op `patch-signals!` —
  about 40 bytes, and a real `datastar-patch-signals` event the browser has to
  process. This is ~10 bytes and nothing to process. the subscription
  registry is what will call it.

  `text` must not contain a newline: an SSE comment is one line, so an embedded
  `\\n` would end the comment and inject whatever followed as a stream field.
  Callers pass a literal (`\"ping\"`); this does not defend against them."
  ^Appendable [^Appendable appendable ^String text]
  (doto appendable
    (.append ": ")
    (.append text)
    (.append "\n\n")))
