(defn split-data-lines
  "Split `text` into SSE data lines the way the wire requires, using Java's
  `String.lines()`.

  **`.lines()`, not `clojure.string/split-lines`, and this is the finding the
  whole slice exists to produce.** The two agree on `\\n` and on `\\r\\n` and
  disagree on a **lone `\\r`**:

      (split-data-lines \"a\\rb\")            => [\"a\" \"b\"]     ; .lines()
      (str/split-lines  \"a\\rb\")            => [\"a\\rb\"]      ; passes it through

  A lone `\\r` is a line terminator per the SSE spec, so `.lines()` is right and
  `split-lines` ships a `\\r` inside a `data:` line. The browser's parser then
  ends the field at the `\\r` and reads the remainder — `b` above — as the *name*
  of the next field, which it does not recognise, so it **silently discards it**.
  The element truncates. No exception is thrown anywhere, on either side.

  That is not a hypothetical: a lone `\\r` arrives in every string we did not
  author — var docstrings, ledger content, fetched pages — and the original namespace-browser example
  renders docstrings straight into a `<pre>`. We would have shipped it, and the
  symptom (some panels truncate, sometimes) reads as a rendering bug, not a wire
  bug.

  There are two more divergences, and the third was **not** predicted by the
  plan — it fell out of running `split-lines` through the differential harness
  as a negative control (3 of 18 payloads diverge, not 1):

  - `\"\"`: `.lines()` yields `[]`, `split-lines` yields `[\"\"]`. This is why a
    blank payload must emit no `elements` line at all rather than an empty one
    — see `->patch-elements`.
  - **trailing blank lines**: `split-lines` is `(str/split s #\"\\r?\\n\")`, and
    `split` with no limit **drops trailing empty strings**. So `\"a\\n\\n\"`
    becomes `[\"a\"]` there and `[\"a\" \"\"]` here. Rendered HTML and markdown
    end with a newline constantly, so this fires far more often than the `\\r`
    case; it is just less dramatic — you lose a trailing blank line inside a
    `<pre>` rather than truncating an element.

  Returns a vector so the result is a value with no stream semantics attached."
  [prefix ^String text]
  (into [] (map #(str prefix %)) (iterator-seq (.iterator (.lines text)))))

