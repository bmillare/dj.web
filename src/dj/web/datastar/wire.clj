(def ^:private element-opt-keys
  (array-map selector                 "selector"
             patch-mode               "mode"
             use-view-transition      "useViewTransition"
             view-transition-selector "viewTransitionSelector"
             element-namespace        "namespace"))

(def ^:private signals-opt-keys
  (array-map only-if-missing "onlyIfMissing"))

(def ^:private sse-opt-keys
  #{:d*.sse/id :d*.sse/retry-duration})

(def ^:private patch-modes
  #{"remove" "outer" "inner" "replace" "prepend" "append" "before" "after"})

(defn- reject-unknown-opts! [opts known op]
  (when-let [ks (not-empty (filterv #(not (contains? known %)) (keys opts)))]
    (throw (ex-info (str "dj.web.datastar.wire/" op " received unknown option "
                         (str/join ", " (map pr-str ks)))
                    {:unknown ks :op op}))))

(defn- validate-patch-mode! [mode op]
  (when-not (contains? patch-modes mode)
    (throw (ex-info (str "dj.web.datastar.wire/" op
                         " received unsupported patch mode " (pr-str mode))
                    {:patch-mode mode :supported patch-modes :op op}))))

(defn- reject-unsupported-opts!
  "Throw if `opts` carries a layer-2 option this stack does not implement.

  The alternative — ignore it — is the exact failure mode this layer is prone
  to: an omitted option changes UI behavior without an error.

  Rejects on *presence*, not truthiness, so an unsupported nil cannot appear to
  have been accepted."
  [opts known op]
  (when-let [ks (not-empty (filterv #(contains? opts %) (keys known)))]
    (throw (ex-info (str "dj.web.datastar.wire/" op " does not implement "
                         (str/join ", " (map known ks)))
                    {:unsupported ks :op op}))))

(def ^:private unsupported-element-opt-keys
  (select-keys element-opt-keys
               [use-view-transition view-transition-selector element-namespace]))

;; -----------------------------------------------------------------------------
;; The two operations
;; -----------------------------------------------------------------------------

(defn ->patch-elements
  "Data lines for a `datastar-patch-elements` event: one `elements <line>` per
  line of `elements`. Same signature and same output as
  `starfederation.datastar.clojure.api.elements/->patch-elements` on the subset
  we implement (`selector` and `mode`), which `wire-test` asserts over its full
  cross-product.

      (->patch-elements \"<div>x</div>\" {})   => [\"elements <div>x</div>\"]
      (->patch-elements \"a\\nb\" {})           => [\"elements a\" \"elements b\"]
      (->patch-elements \"\" {})               => []

  **A blank payload emits nothing, not an empty line.** Whitespace-only counts
  as blank, so `\" \\n \"` is `[]` too. This is the rule that makes the SDK's
  `remove-element!` work: it is `patch-elements!` with an empty body and
  `mode remove`, and an `elements ` line with nothing after it would be a patch
  of the empty string rather than a removal.

  Note the composition with `split-data-lines`: for a *non*-blank payload the
  blank check is already redundant with `.lines()` returning `[]` on `\"\"` — but
  only for `\"\"` exactly. `\"  \"` is non-empty to `.lines()` and blank to
  `str/blank?`, and the SDK suppresses it. Two rules that look like one."
  [^String elements opts]
  (reject-unknown-opts! opts
                        (into sse-opt-keys (keys element-opt-keys))
                        "patch-elements!")
  (reject-unsupported-opts! opts unsupported-element-opt-keys "patch-elements!")
  (let [selector-value (get opts selector "")
        mode-value     (get opts patch-mode "outer")]
    (assert (string? selector-value) "Datastar selector must be a String")
    (assert (string? mode-value) "Datastar patch mode must be a String")
    (validate-patch-mode! mode-value "patch-elements!")
    (cond-> []
      (not (str/blank? selector-value)) (conj (str "selector " selector-value))
      (and (not (str/blank? mode-value)) (not= "outer" mode-value))
      (conj (str "mode " mode-value))
      (not (str/blank? elements))
      (into (split-data-lines elements-dataline-literal elements)))))

(defn ->patch-signals
  "Data lines for a `datastar-patch-signals` event: one `signals <line>` per line
  of the JSON text in `signals`. Same rules as `->patch-elements` — blank emits
  nothing, `.lines()` does the splitting.

      (->patch-signals \"{\\\"a\\\":1}\" {})   => [\"signals {\\\"a\\\":1}\"]

  The multi-line case is not an edge case to tolerate but the normal one for
  pretty-printed JSON, and it is why `signals` is a data line rather than a
  header: SSE has no way to carry a raw newline in a field, so every producer
  has to split. We take JSON as a **String**, not a map, for the same reason the
  SDK does — the caller owns the encoder (`clojure.data.json` here), and a map
  argument would silently pick one."
  [^String signals opts]
  (reject-unknown-opts! opts
                        (into sse-opt-keys (keys signals-opt-keys))
                        "patch-signals!")
  (reject-unsupported-opts! opts signals-opt-keys "patch-signals!")
  (if (str/blank? signals)
    []
    (split-data-lines signals-dataline-literal signals)))
