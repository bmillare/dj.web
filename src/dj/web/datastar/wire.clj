(ns dj.web.datastar.wire
  "**Letters.** The Datastar wire semantics: which data lines an operation
  produces, in which order, and how a payload string becomes N of them. It
  produces a vector of strings and has no idea that an SSE frame exists. Plus
  the one thing that travels the other way — `get-signals`, which says where on
  an incoming request Datastar puts the client's store (layer 6).

  Its counterpart is `dj.web.sse` (the envelopes), and the two do not know about each
  other — the value passed between them is a plain vector of strings, which is
  what lets either one independently be ours or the SDK's:

      semantic op          data lines              frame bytes          socket
      patch-elements  ->   [\"mode append\"    ->   event: ...\\n     ->   OutputStream
      html + opts          \"elements <div>\"]      data: mode append\\n
                                                  data: elements ...\\n
                                                  \\n
      layer 2 (HERE)       layer 3                 layer 4
      \"the letters\"        dj.web.sse         dj.web.datastar

  **This namespace must never require `starfederation.*`, nor `dj.web.sse`.**
  It is pure: string (or a request map) in, plain values out; no protocol, no
  IO, no lock — `get-signals` hands back the request's `:body` stream without
  reading it, and the JSON parse belongs to the layer above. A transport such as
  `dj.web.datastar.reference` composes these values with SSE and a socket.

  The owned element surface is intentionally small: `selector` and `mode`, plus
  the payload lines. `useViewTransition`, `viewTransitionSelector`, `namespace`,
  and the signal option `onlyIfMissing` are rejected on presence instead of
  silently disappearing. Incoming signals are returned from the correct request
  location without doing IO here.

  Tiny as it is, this is where being wrong is *silent*, and it contains the
  sharpest lesson in the plan — see `split-data-lines`."
  (:require [clojure.string :as str]))

