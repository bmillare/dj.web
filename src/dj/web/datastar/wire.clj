(defn get-signals
  "The client's signals as Datastar put them on `request`, **unparsed**: a
  String for `GET`/`DELETE`, the `:body` InputStream for everything else, `nil`
  if there are none. Same rule and same return types as
  `starfederation.datastar.clojure.api/get-signals`, which `wire-test` diffs
  over the method matrix. Parsing is `dj.web.datastar/signals`.

  Two return types rather than one because the split is not ours to make: a
  `GET` has no body, so the store rides in a query param and arrives already
  decoded as a String, while `POST`/`PUT`/`PATCH` carry it as bytes we have not
  read yet. Slurping the stream here would make this layer do IO and would
  consume a one-shot stream on behalf of a caller that might not want it.

  **This is the request-side extraction, and it is the seam where a non-ring server diverges in
  silence** — which is the only reason a three-line function got its own slice.
  We are not ring: `dj.web.http/query-params` is ours, and this function
  asserts that it parsed the query string the way ring would. Get the collision
  rule wrong (ring: one occurrence is a String, two make a **vector**) and a
  duplicated `datastar` param hands a vector to `json/read-str`, which reports a
  type error about a value nobody wrote. Get the decoding wrong — split a
  decoded query string rather than the raw one — and a `%26` inside the JSON
  ends the param early, so the signals are truncated rather than absent.
  `http-test/signals-in` drives a real `@get`-shaped URL through the server for
  exactly this reason; the differential here only pins the lookup.

  String key, not keyword: that is ring's shape for `:query-params`, and it is
  where the SDK looks. Keywordizing query params would be a second convention
  for the same map."
  [request]
  (case (:request-method request)
    (:get :delete) (get-in request [:query-params datastar-key])
    (:body request)))

(defn datastar-request?
  "True when `request` came from a Datastar action (`@get`, `@post`, ...) rather
  than a plain page load — useful for handlers that serve both.

  **Exact** equality against `\"true\"`, not presence and not a case-insensitive
  compare, because that is the rule: the client sets the header to that literal,
  so anything else did not come from the client we are talking about. Two ways
  our own HTTP layer can produce an \"anything else\" worth knowing about:

  - `dj.web.http/request-headers` **lower-cases** every header name (ring's
    shape), which is why the key here is lower-case. Look for `Datastar-Request`
    and every action request reads as a page load.
  - it also **comma-joins** a header that arrives more than once, so a doubled
    header gives `\"true,true\"` — false here, correctly. A `str/includes?`
    would have said true, and would also have said true for `\"untrue\"`."
  [request]
  (= "true" (get-in request [:headers datastar-request-header])))

