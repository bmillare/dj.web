(ns dj.web.sse-test
  "Layer 3, the **envelopes**: `dj.web.sse` diffed against
  `starfederation.datastar.clojure.api.sse` over the shared matrix in
  `dj.web.wire-matrix` (which explains the method).

  Extraction stages asserted here: **1** (frame assembly, `write-event!`, `write-comment!`),
  the half of **2** that landed on this side of the boundary
  (`normalize-event-opts`, which was the SDK's private `rework-options` until
  owning layer 2 moved the entry point past it), and **5** — layer 5, the
  response headers.

  the header extraction is the first one whose central function has **no oracle**:
  `acceptable-encoding?` is asserted against RFC 9110 rather than against the
  SDK, because the SDK never asks the question. That is not a gap in the method,
  it is what the method is for — the differential pins everything the SDK does,
  and what is left over is the capability owning the layer bought.

  Also here: the byte-level check on the adapter's write path, because that is
  where this layer meets a real `OutputStream`."
  (:require [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [dj.web.datastar :as ds]
            [dj.web.sse :as sse]
            [dj.web.wire-matrix :as m]
            [starfederation.datastar.clojure.adapter.common :as ac]
            [starfederation.datastar.clojure.api.common :as sdk-common]
            [starfederation.datastar.clojure.api.elements :as sdk-elements]
            [starfederation.datastar.clojure.api.signals :as sdk-signals]
            [starfederation.datastar.clojure.api.sse :as sdk-sse]
            [starfederation.datastar.clojure.consts :as sdk-consts])
  (:import [java.io ByteArrayOutputStream Writer]
           [java.nio.charset StandardCharsets]))

