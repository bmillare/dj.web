(deftest sse-literals-match-the-sdk
  (testing "the option keywords and default `write-event!` reads are the SDK's"
    ;; The whole the literal-compatibility check idea in three assertions. `consts.clj` upstream carries
    ;; "auto-generated by Datastar. DO NOT EDIT" — the literals are generated
    ;; from the spec across every language SDK at once, while ours are
    ;; hand-written. Keeping the jar in :deps turns it from a dependency into a
    ;; spec tracker: a `clj -Sforce -M:test` after an SDK bump tells us the wire
    ;; moved, here, instead of in a browser.
    (is (= sdk-common/id sse/id))
    (is (= sdk-common/retry-duration sse/retry-duration))
    (is (= sdk-consts/default-sse-retry-duration sse/default-retry-duration))))

;; -----------------------------------------------------------------------------
;; the framing extraction — frame assembly
;; -----------------------------------------------------------------------------

(defn- sdk-frame [event-type data-lines opts]
  (str (sdk-sse/write-event! (StringBuilder.) event-type data-lines opts)))

(defn- our-frame [event-type data-lines opts]
  (str (sse/write-event! (StringBuilder.) event-type data-lines opts)))

(deftest frame-assembly-matches-the-sdk-on-the-id-retry-matrix
  (testing "event:/id:/retry:/data:/terminator, over every id x retry x shape"
    (let [d (m/diffs m/frame-cases
                     #(our-frame (:event-type %) (:data-lines %) (:opts %))
                     #(sdk-frame (:event-type %) (:data-lines %) (:opts %)))]
      (is (empty? d) (m/report d)))))

(deftest frame-assembly-matches-the-sdk-on-real-data-lines
  (testing "3,888 element payloads, framed"
    ;; Data lines come from the SDK here even though we now own that layer too —
    ;; on purpose. This is a layer-3 test, and feeding it layer-2 output from
    ;; the oracle keeps a bug in one layer from hiding a bug in the other.
    (let [d (m/diffs m/element-cases
                     #(our-frame sdk-consts/event-type-patch-elements
                                 (sdk-elements/->patch-elements (:elements %) (:opts %))
                                 {})
                     #(sdk-frame sdk-consts/event-type-patch-elements
                                 (sdk-elements/->patch-elements (:elements %) (:opts %))
                                 {}))]
      (is (empty? d) (m/report d))))
  (testing "and the signals payloads"
    (let [d (m/diffs m/signals-cases
                     #(our-frame sdk-consts/event-type-patch-signals
                                 (sdk-signals/->patch-signals (:signals %) (:opts %))
                                 {})
                     #(sdk-frame sdk-consts/event-type-patch-signals
                                 (sdk-signals/->patch-signals (:signals %) (:opts %))
                                 {}))]
      (is (empty? d) (m/report d)))))

(deftest the-frame-is-what-we-think-it-is
  (testing "the oracle agreeing is not the same as the wire being right"
    ;; Two implementations can agree and both be wrong. One literal assertion,
    ;; written from the SSE spec rather than from either implementation, is what
    ;; keeps the differential tests from being self-referential.
    (is (= "event: datastar-patch-elements\ndata: elements <div>x</div>\n\n"
           (our-frame "datastar-patch-elements" ["elements <div>x</div>"] {})))
    (is (= (str "event: datastar-patch-elements\n"
                "id: e1\n"
                "retry: 500\n"
                "data: selector #x\n"
                "data: elements a\n"
                "data: elements b\n"
                "\n")
           (our-frame "datastar-patch-elements"
                      ["selector #x" "elements a" "elements b"]
                      {sse/id "e1" sse/retry-duration 500}))))
  (testing "an event with no data lines is still a terminated frame"
    (is (= "event: datastar-patch-elements\n\n"
           (our-frame "datastar-patch-elements" [] {})))))

(deftest write-event-returns-the-appendable
  ;; The SDK's does (it is a `doto`), and `->send`'s temp-buffer path relies on
  ;; it to `str` the builder in one expression.
  (let [sb (StringBuilder.)]
    (is (identical? sb (sse/write-event! sb "e" [] {})))))

;; -----------------------------------------------------------------------------
;; the wire extraction's other half — option normalization, now ours
;; -----------------------------------------------------------------------------

(def ^:private sdk-rework
  "`sse/rework-options` is **private** and runs inside `sse/send-event!`, i.e.
  upstream of the generator's `p/send-event!`. It was therefore upstream of us
  too, for exactly as long as calls entered through `d*/patch-elements!`. the wire extraction
  moved the entry point to `ds/patch-elements!`, so it is ours now — and this is
  the oracle for it."
  @#'sdk-sse/rework-options)

(deftest normalize-event-opts-matches-the-private-sdk-rework
  (testing "over the full id x retry matrix"
    ;; The trap this slice was one step away from, now landed. Had we moved the
    ;; entry point without bringing the normalization along, blank ids and
    ;; redundant `retry: 1000` lines would have reached the wire and no test
    ;; that goes through a facade would have seen it — because we are the
    ;; facade now.
    (let [cases (vec (for [[ik id]    m/ids
                           [rk retry] m/retries]
                       {:label {:id ik :retry rk}
                        :opts  (-> {}
                                   (m/assoc-some sdk-common/id id)
                                   (m/assoc-some sdk-common/retry-duration retry))}))
          ;; `false` for id/retry is what normalization *produces*; feeding it
          ;; back in is a type error on both sides, so those rows are skipped.
          cases (filterv #(and (not= :dropped (-> % :label :id))
                               (not= :dropped (-> % :label :retry)))
                         cases)
          d (m/diffs cases
                     #(sse/normalize-event-opts (:opts %))
                     #(sdk-rework (:opts %)))]
      (is (empty? d) (m/report d)))))

(deftest normalize-event-opts-drop-rules
  (testing "what the rules are, stated rather than inherited"
    ;; Note the value: a dropped option comes back **`false`, not `nil`**, and
    ;; both keys are always present — normalization builds a fresh 2-key map
    ;; with `(and (keep? v) v)`. So the contract `write-event!` actually has to
    ;; honour is "emit when truthy", never `(contains? opts id)` and never
    ;; `(some? (get opts id))`; either of those puts `id: false` on the wire on
    ;; the *default* path. This assertion is here because the first version of
    ;; it guessed `nil` and was wrong.
    (is (= {sse/id false sse/retry-duration false} (sse/normalize-event-opts {}))
        "defaults: no id, and 1000ms retry is Datastar's default")
    (is (false? (sse/id (sse/normalize-event-opts {sse/id ""})))
        "a blank id is dropped, not emitted as `id: `")
    (is (false? (sse/id (sse/normalize-event-opts {sse/id "   "})))
        "and whitespace-only counts as blank")
    (is (= "e1" (sse/id (sse/normalize-event-opts {sse/id "e1"}))))
    (is (false? (sse/retry-duration (sse/normalize-event-opts {sse/retry-duration 0})))
        "0 means 'no retry line', not 'retry immediately'")
    (is (false? (sse/retry-duration (sse/normalize-event-opts {sse/retry-duration 1000})))
        "the default duration is never put on the wire")
    (is (= 500 (sse/retry-duration (sse/normalize-event-opts {sse/retry-duration 500})))))
  (testing "and composed with our framing it drops the lines, not just the keys"
    (is (= "event: e\n\n" (our-frame "e" [] (sse/normalize-event-opts {sse/id ""}))))
    (is (= "event: e\n\n" (our-frame "e" [] (sse/normalize-event-opts
                                             {sse/retry-duration 1000}))))
    (is (= "event: e\nid: e1\n\n" (our-frame "e" [] (sse/normalize-event-opts
                                                     {sse/id "e1"})))))
  (testing "a wrong-typed option is named at the call site"
    (is (thrown? AssertionError (sse/normalize-event-opts {sse/id :not-a-string})))
    (is (thrown? AssertionError (sse/normalize-event-opts {sse/retry-duration "500"})))))

