(deftest comment-frames
  (testing "a heartbeat is ten bytes and not an event"
    (let [frame (str (sse/write-comment! (StringBuilder.) "ping"))]
      (is (= ": ping\n\n" frame))
      ;; The reason this cannot be done through the SDK: every path into a
      ;; generator goes through `p/send-event!`, which writes `event: <type>`
      ;; before anything else, so the cheapest SDK heartbeat is a no-op
      ;; `patch-signals!` — ~40 bytes and a real client-side event.
      (is (not (str/includes? frame "event:")))
      (is (< (count frame)
             (count (our-frame sdk-consts/event-type-patch-signals
                               (sdk-signals/->patch-signals "{}" {})
                               {})))))))

;; -----------------------------------------------------------------------------
;; the header extraction — layer 5, the response headers
;; -----------------------------------------------------------------------------

(defn- sdk-headers
  "The oracle, called the way the SDK is shaped: the coding reaches `ac/headers`
  only as a property of a write profile, never as an argument. Building a
  one-key profile here is not a contrivance — it is the SDK's *only* way to ask
  for a `Content-Encoding`, and that is the constraint the header extraction is about."
  [request encoding extra]
  (ac/headers request {ac/write-profile {ac/content-encoding encoding}
                       :headers         extra}))

(deftest headers-match-the-sdk-on-every-protocol-and-coding
  (testing "90 cases: 6 protocols x 3 codings x 5 caller-header shapes"
    (let [d (m/diffs m/sse-header-cases
                     #(sse/headers (:request %) (:encoding %) (:extra %))
                     #(sdk-headers (:request %) (:encoding %) (:extra %)))]
      (is (empty? d) (m/report d)))))

(defn- naive-keep-alive-headers
  "What you write if you implement the ADR's text and remember the one exception
  everybody remembers: `Connection: keep-alive` everywhere **except HTTP/2**,
  named explicitly. Kept executable as a negative control, for the same reason
  `naive-split` is in `wire-test`."
  [request encoding extra]
  (-> sse/base-headers
      (cond-> (not= "HTTP/2" (:protocol request)) (assoc "Connection" "keep-alive")
              encoding (assoc "Content-Encoding" encoding))
      (merge extra)))

(deftest the-keep-alive-rule-is-below-1-1-not-at-it
  (testing "naming HTTP/2 instead of ordering versions diverges on 1.1 AND 3"
    ;; The rule this layer is worth owning for. `Connection` is redundant from
    ;; HTTP/1.1 on (persistent is the default) and FORBIDDEN in HTTP/2 — RFC
    ;; 9113 §8.2.2 makes it a connection-specific field a peer must treat as
    ;; malformed, and RFC 9114 §4.2 says the same for HTTP/3.
    ;;
    ;; HTTP/1.1 is the divergence this control was written to produce: the ADR
    ;; says set the header *for* 1.1, and the SDK deliberately doesn't. **HTTP/3
    ;; was not predicted** — it fell out of running the control, exactly as the
    ;; third `split-lines` divergence did in `wire-test`. That is the finding: a
    ;; correct-looking implementation encodes the exception it remembers by
    ;; name, and is then wrong for every version that ships after it is written.
    ;; `(neg? (compare protocol "HTTP/1.1"))` is not a terser spelling of the
    ;; same rule — it is a rule about ordering, so it covers versions that did
    ;; not exist when it was written.
    (let [d (m/diffs m/sse-header-cases
                     #(naive-keep-alive-headers (:request %) (:encoding %) (:extra %))
                     #(sdk-headers (:request %) (:encoding %) (:extra %)))]
      (is (= #{:http-1.1 :http-3} (into #{} (map (comp :protocol :label)) d))
          (str "the negative control found: " (pr-str (mapv :label d))))))
  (testing "and nil sorts below every protocol, so an absent one keeps alive"
    ;; `compare` does this, not the explicit nil? clause — worth an assertion
    ;; because the redundancy is only safe in one direction.
    (is (= "keep-alive" (get (sse/headers nil nil nil) "Connection")))
    (is (= "keep-alive" (get (sse/headers {:protocol "HTTP/1.0"} nil nil) "Connection")))
    (is (nil? (get (sse/headers {:protocol "HTTP/1.1"} nil nil) "Connection")))
    (is (nil? (get (sse/headers {:protocol "HTTP/2"} nil nil) "Connection")))
    (is (nil? (get (sse/headers {:protocol "HTTP/3"} nil nil) "Connection"))
        "a version the rule predates, which is the reason it is a comparison")))

(deftest the-headers-are-what-we-think-they-are
  (testing "written from the spec, not from either implementation"
    ;; Two implementations can agree and both be wrong.
    (is (= {"Cache-Control" "no-cache"
            "Content-Type"  "text/event-stream"
            "Connection"    "keep-alive"}
           (sse/headers {:protocol "HTTP/1.0"} nil nil))))
  (testing "the content type is bare — no charset parameter"
    ;; `text/event-stream` is UTF-8 by definition in the HTML spec, and
    ;; `http-test/sse-round-trip` asserts exact equality on the value.
    (is (= "text/event-stream" (get sse/base-headers "Content-Type"))))
  (testing "the caller's headers are merged last and win"
    (is (= "no-store" (get (sse/headers nil nil {"Cache-Control" "no-store"})
                           "Cache-Control")))
    (is (= "close" (get (sse/headers nil nil {"Connection" "close"}) "Connection"))))
  (testing "and Content-Encoding appears only when there is a coding"
    (is (nil? (get (sse/headers nil nil nil) "Content-Encoding")))
    (is (= "gzip" (get (sse/headers nil "gzip" nil) "Content-Encoding")))))

