(deftest acceptable-encoding-follows-rfc-9110
  ;; No differential here: the SDK has no counterpart, which is the whole point
  ;; — `ac/headers` never reads `Accept-Encoding` at all. So these are written
  ;; from RFC 9110 §12.5.3 directly, like `the-headers-are-what-we-think-they-are`
  ;; above and unlike everything with an oracle behind it.
  (let [accepts? (fn [v] (sse/acceptable-encoding?
                          {:headers (cond-> {} v (assoc "accept-encoding" v))}
                          "gzip"))]
    (testing "silence is permission — the plan had this one backwards"
      ;; the extraction design called the SDK's behaviour \"gzips a client that didn't ask\".
      ;; Not asking is not refusing: with no Accept-Encoding field, any content
      ;; coding is acceptable. The defect is narrower than the plan stated.
      (is (true? (accepts? nil)))
      (is (true? (sse/acceptable-encoding? nil "gzip")) "nil request too")
      (is (true? (sse/acceptable-encoding? {} "gzip"))))

    (testing "the three spellings of refusal"
      (is (false? (accepts? "identity")) "listed something else, no wildcard")
      (is (false? (accepts? "gzip;q=0")) "named and rejected")
      (is (false? (accepts? "")) "empty field: no coding at all is wanted"))

    (testing "acceptance"
      (is (true? (accepts? "gzip")))
      (is (true? (accepts? "gzip, deflate, br")))
      (is (true? (accepts? "br;q=1.0, gzip;q=0.5")) "a low q is still a yes")
      (is (true? (accepts? "gzip;q=0.001")) "we rank nothing — only q=0 refuses"))

    (testing "the wildcard stands in for anything unnamed"
      (is (true? (accepts? "*")))
      (is (false? (accepts? "*;q=0")))
      (is (true? (accepts? "gzip, *;q=0")) "named beats the wildcard")
      (is (false? (accepts? "identity, *;q=0"))))

    (testing "the parsing details that a `str/includes?` would get wrong"
      ;; Which is the point of parsing at all: `(str/includes? v \"gzip\")` says
      ;; yes to `gzip;q=0`, and yes to `x-gzip`, which is a different coding.
      (is (true?  (accepts? " GZIP ")) "case-insensitive, whitespace-tolerant")
      (is (true?  (accepts? "gzip ; q=0.7")) "spaces around the parameter")
      (is (false? (accepts? "x-gzip")) "a different coding, not a substring match")
      (is (true?  (accepts? "gzip;q=bogus")) "an unreadable q defaults to 1"))

    (testing "and it is asked about the coding, not told about gzip"
      (is (true? (sse/acceptable-encoding? {:headers {"accept-encoding" "br"}} "br")))
      (is (false? (sse/acceptable-encoding? {:headers {"accept-encoding" "br"}} "gzip"))))))

(deftest a-refused-coding-downgrades-the-profile-not-just-the-header
  (testing "the header and the stream wrapping stay two halves of one decision"
    ;; Suppressing the header alone would be worse than the bug: the profile
    ;; would still wrap the socket in a GZIPOutputStream, so the client would get
    ;; gzip bytes with nothing declaring them. `->sse-response` therefore rewrites
    ;; the opts it hands the generator, and reads the header off the same value.
    (let [request (fn [accept-encoding]
                    {:request-method :get
                     :protocol       "HTTP/1.1"
                     :headers        (cond-> {}
                                       accept-encoding
                                       (assoc "accept-encoding" accept-encoding))})
          opts    {ac/write-profile ac/gzip-profile ac/on-open (fn [_sse] nil)}
          profile #(@#'ds/negotiated-write-profile (request %) opts)
          header  #(get (:headers (ds/->sse-response (request %) opts))
                        "Content-Encoding")]
      (testing "a client that refused gets neither the header nor the gzip"
        (is (= ac/basic-profile (profile "identity")))
        (is (nil? (header "identity"))))
      (testing "a client that accepted gets both"
        (is (= ac/gzip-profile (profile "gzip")))
        (is (= "gzip" (header "gzip"))))
      (testing "and silence is still permission, so nothing changes for a browser"
        (is (= ac/gzip-profile (profile nil)))
        (is (= "gzip" (header nil))))
      (testing "a profile with no coding is never touched"
        ;; The refusal path must not fire for the profile everything actually
        ;; uses — there is nothing to negotiate about an uncompressed stream.
        (is (= ac/basic-profile
               (@#'ds/negotiated-write-profile (request "identity")
                                               {ac/on-open (fn [_sse] nil)})))))))

;; -----------------------------------------------------------------------------
;; The swap point: the adapter's write path, byte for byte
;; -----------------------------------------------------------------------------

(defn- bytes-via-sdk-profile
  "What `->send` used to emit: the profile's own `ac/write!`."
  [profile event-type data-lines opts]
  (let [baos    (ByteArrayOutputStream.)
        wrapped ((ac/wrap-output-stream profile) baos)]
    ((ac/write! profile) wrapped event-type data-lines opts)
    (.flush ^Writer wrapped)
    (.toByteArray baos)))

(defn- bytes-via-our-send
  "What `->send` emits now: our buffering decision plus `sse/write-event!`."
  [profile event-type data-lines opts]
  (let [baos  (ByteArrayOutputStream.)
        send! (@#'ds/->send baos {ac/write-profile profile})]
    (send! event-type data-lines opts)
    (.toByteArray baos)))

(deftest send-path-is-byte-identical-to-the-sdk-profiles
  (testing "both stock uncompressed profiles, over the full frame matrix"
    ;; This is what makes the `->send` change a *swap* rather than a rewrite:
    ;; we stopped reading the profile's `write!` key and now decide buffering
    ;; from the wrapped stream, so the buffered profile takes the write-through
    ;; branch that the SDK reserves for its gzip variant. Same bytes either way
    ;; — which is precisely the claim under test.
    (doseq [[pname profile] (array-map :basic    ac/basic-profile
                                       :buffered ac/buffered-writer-profile)]
      (let [d (m/diffs m/frame-cases
                       #(String. ^bytes (bytes-via-our-send profile (:event-type %)
                                                            (:data-lines %) (:opts %))
                                 StandardCharsets/UTF_8)
                       #(String. ^bytes (bytes-via-sdk-profile profile (:event-type %)
                                                               (:data-lines %) (:opts %))
                                 StandardCharsets/UTF_8))]
        (is (empty? d) (str pname " profile: " (m/report d))))))
  (testing "UTF-8 survives the buffering decision"
    ;; The two branches encode at different moments (String -> writer, versus
    ;; field by field into a BufferedWriter), so a multi-byte character is worth
    ;; asserting at the byte level rather than trusting the String comparison.
    (doseq [profile [ac/basic-profile ac/buffered-writer-profile]]
      (is (= (seq (.getBytes "event: e\ndata: elements <p>an em — dash</p>\n\n"
                             StandardCharsets/UTF_8))
             (seq (bytes-via-our-send profile "e"
                                      ["elements <p>an em — dash</p>"] {})))))))
