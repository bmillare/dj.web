(deftest patch-elements-matches-the-sdk-on-every-owned-shape
  (testing "18 payloads crossed with selector and mode"
    (let [cases (filterv #(every? #{wire/selector wire/patch-mode}
                                  (keys (:opts %)))
                         m/element-cases)
          d (m/diffs cases
                     #(wire/->patch-elements (:elements %) (:opts %))
                     #(sdk-elements/->patch-elements (:elements %) (:opts %)))]
      (is (empty? d) (m/report d)))))

(deftest patch-signals-matches-the-sdk-on-every-payload
  (testing "8 JSON shapes, no options"
    (let [d (m/diffs m/signals-cases-no-opts
                     #(wire/->patch-signals (:signals %) (:opts %))
                     #(sdk-signals/->patch-signals (:signals %) (:opts %)))]
      (is (empty? d) (m/report d)))))

;; -----------------------------------------------------------------------------
;; The finding this slice exists to produce
;; -----------------------------------------------------------------------------

(defn- naive-split
  "What the obvious Clojure implementation of `split-data-lines` would be. Kept
  as an executable negative control rather than a comment: running it through
  the same matrix is what proves the harness is not vacuous, and it is how the
  trailing-newline divergence below was found — the plan predicted only the
  lone `\\r`."
  [prefix text]
  (mapv #(str prefix %) (str/split-lines text)))

(deftest the-harness-catches-the-mistake-it-was-built-to-catch
  (testing "swapping in `split-lines` diverges from the oracle on 3 of 18 payloads"
    ;; the differential harness's claim is that the differential matrix would have caught the
    ;; layer-2 mistakes. That claim is worth testing directly, because a matrix
    ;; whose axes happen to miss the bug passes just as quietly as a correct
    ;; implementation. These are the three, by label:
    ;;   :cr       "a\rb"    -> ["elements a\rb"]  vs ["elements a" "elements b"]
    ;;   :mixed    "a\nb\rc\r\nd"
    ;;   :trailing "a\n\n"   -> ["elements a"]     vs ["elements a" "elements "]
    (let [d (m/diffs m/element-cases-no-opts
                     #(if (str/blank? (:elements %))
                        []
                        (naive-split wire/elements-dataline-literal (:elements %)))
                     #(sdk-elements/->patch-elements (:elements %) (:opts %)))]
      (is (= #{:cr :mixed :trailing} (into #{} (map (comp :elements :label)) d))
          (str "the negative control found: "
               (pr-str (mapv :label d)))))))

(deftest split-lines-would-have-been-wrong
  (testing "`.lines()` and `split-lines` diverge on a lone \\r, and it is silent"
    ;; The defect we did not ship. A lone `\r` is a line terminator per the SSE
    ;; spec, so it MUST become a new `data:` line. Leave it inside one and the
    ;; browser ends the field at the `\r` and reads the rest as the *name* of an
    ;; unrecognised field, which it discards without a word: the element simply
    ;; truncates. Nothing throws on either side of the socket.
    ;;
    ;; This is not exotic input. A lone `\r` arrives in every string we did not
    ;; author — var docstrings, ledger content, fetched pages — and the original namespace-browser example
    ;; renders docstrings straight into a `<pre>`.
    (is (= ["elements a" "elements b"] (wire/->patch-elements "a\rb" {})))
    (is (= ["elements a\rb"] (naive-split "elements " "a\rb"))
        "what the obvious Clojure implementation would have produced"))
  (testing "and a trailing newline, which the plan did not predict"
    ;; `split-lines` is `(split s #\"\r?\n\")`, and `split` drops trailing empty
    ;; strings. Rendered HTML and markdown end in a newline constantly, so this
    ;; one fires far more often than the `\r` — it is just quieter, costing a
    ;; blank line inside a `<pre>` rather than truncating an element.
    (is (= ["elements a" "elements "] (wire/->patch-elements "a\n\n" {})))
    (is (= ["elements a"] (naive-split "elements " "a\n\n"))))
  (testing "and they agree everywhere a naive test would think to look"
    ;; Which is the point: `\n` and `\r\n` are what anyone writes a test for.
    (is (= (wire/->patch-elements "a\nb" {}) (naive-split "elements " "a\nb")))
    (is (= (wire/->patch-elements "a\r\nb" {}) (naive-split "elements " "a\r\nb")))))

(deftest blank-suppression-is-a-separate-rule-from-splitting
  (testing "a blank payload emits no line at all, not an empty one"
    ;; This is what makes the SDK's `remove-element!` work — it is
    ;; `patch-elements!` with an empty body and `mode remove`, and an `elements `
    ;; line with nothing after it would be a patch of the empty string rather
    ;; than a removal.
    (is (= [] (wire/->patch-elements "" {})))
    (is (= [] (wire/->patch-signals "" {}))))
  (testing "whitespace-only counts as blank, which splitting alone would not catch"
    ;; `.lines()` returns `[]` for `""` — so for that one input the blank guard
    ;; looks redundant. It is not: `"  "` and `"\n"` are both non-empty to
    ;; `.lines()` and blank to `str/blank?`, and the SDK suppresses both. Two
    ;; rules that look like one.
    (is (= [] (wire/->patch-elements "  " {})))
    (is (= [] (wire/->patch-elements "\n" {})))
    (is (= [] (wire/->patch-elements "\r" {})))
    (is (= ["elements "] (wire/split-data-lines wire/elements-dataline-literal "\n"))
        "the splitter on its own would have emitted the empty line")))

(deftest the-lines-are-what-we-think-they-are
  (testing "written from the Datastar spec, not from either implementation"
    ;; Two implementations can agree and both be wrong; the differential tests
    ;; are only as good as the literal ones next to them.
    (is (= ["elements <div>x</div>"] (wire/->patch-elements "<div>x</div>" {})))
    (is (= ["elements a" "elements b"] (wire/->patch-elements "a\nb" {})))
    (is (= ["elements a" "elements b"] (wire/->patch-elements "a\r\nb" {})))
    (is (= ["signals {\"a\":1}"] (wire/->patch-signals "{\"a\":1}" {})))
    (is (= ["signals {" "signals   \"a\": 1" "signals }"]
           (wire/->patch-signals "{\n  \"a\": 1\n}" {}))
        "pretty-printed JSON is the normal case, not an edge one"))
  (testing "a payload that looks like SSE syntax is content, never syntax"
    ;; Layer 3 adds `data: `; a payload is never parsed on the way out.
    (is (= ["elements data: not-a-field"] (wire/->patch-elements "data: not-a-field" {})))
    (is (= ["elements : not-a-comment"] (wire/->patch-elements ": not-a-comment" {})))))

