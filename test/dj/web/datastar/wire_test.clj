(deftest unimplemented-options-throw-instead-of-vanishing
  (testing "every unsupported layer-2 option key is refused by name"
    ;; Ignoring one does not error; it merely changes UI behavior silently.
    (doseq [k [wire/use-view-transition wire/view-transition-selector
               wire/element-namespace]]
      (is (thrown? clojure.lang.ExceptionInfo
                   (wire/->patch-elements "<div>x</div>" {k "whatever"}))
          (str "expected " k " to be refused")))
    (is (thrown? clojure.lang.ExceptionInfo
                 (wire/->patch-signals "{\"a\":1}" {wire/only-if-missing true}))))
  (testing "presence is what is refused, not truthiness"
    ;; A present unsupported key is rejected even when its value would produce
    ;; no line. Otherwise adding an option can silently change nothing.
    (is (thrown? clojure.lang.ExceptionInfo
                 (wire/->patch-elements "<div>x</div>"
                                       {wire/use-view-transition nil}))))
  (testing "SSE event options pass through untouched"
    ;; `id`/`retry` live in the same opts map and belong to layer 3. Refusing
    ;; them here would break `ds/patch-elements!`, which hands one map to both.
    (is (= ["elements <div>x</div>"]
           (wire/->patch-elements "<div>x</div>" {:d*.sse/id "e1"
                                                  :d*.sse/retry-duration 500})))))
