(deftest get-signals-matches-the-sdk-on-every-method
  (testing "8 methods x 4 payload placements — including the mismatched ones"
    ;; The rule is a `case` over `(:get :delete)` with a default, so the cases
    ;; that matter are the ones where method and placement disagree: a `:get`
    ;; carrying a body must still read the query param (and answer nil when
    ;; there isn't one) rather than fall through to the body it does have.
    (let [d (m/diffs m/signals-request-cases
                     #(wire/get-signals (:request %))
                     #(sdk-signals/get-signals (:request %)))]
      (is (empty? d) (m/report d)))))

(defn- naive-get-signals
  "What the obvious Clojure implementation would be: *look in the query param,
  fall back to the body.* Kept as an executable negative control for the same
  reason `naive-split` is — a differential that only ever agrees has proven
  nothing about the axes it crosses."
  [request]
  (or (get-in request [:query-params "datastar"]) (:body request)))

(deftest the-method-axis-is-not-decoration
  (testing "`or` instead of a method `case` diverges on 14 of 32 requests"
    ;; The reason `signals-request-cases` crosses its two axes instead of
    ;; listing them. `or` looks equivalent — every request in an app carries its
    ;; payload in exactly one pocket, so the two agree on all 16 of those. They
    ;; part on the mismatched ones, and the direction matters: a `:get` with a
    ;; body reads that body under `or`, which is how a request with stale bytes
    ;; on it (or a proxy that adds some) turns into signals nobody sent.
    (let [d (m/diffs m/signals-request-cases
                     #(naive-get-signals (:request %))
                     #(sdk-signals/get-signals (:request %)))]
      (is (= 14 (count d)))
      (is (contains? (into #{} (map :label) d) {:method :get :payload :body})
          "the case that shows it is a `case`, not a fallback"))))

(deftest get-signals-reads-the-pocket-the-method-implies
  (testing "written from the Datastar spec, not from either implementation"
    ;; `@get`/`@delete` have no body, so the store rides in a query param;
    ;; everything else carries it as bytes. Two return types, one function —
    ;; the split is Datastar's, not a convenience of ours.
    (let [json "{\"query\":\"dj http\"}"]
      (is (= json (wire/get-signals {:request-method :get
                                     :query-params {"datastar" json}})))
      (is (= json (wire/get-signals {:request-method :delete
                                     :query-params {"datastar" json}})))
      (is (nil? (wire/get-signals {:request-method :get :query-params {}}))
          "no signals at all is nil, not a parse error")
      (is (nil? (wire/get-signals {:request-method :get
                                   :query-params {"other" json}}))
          "and it is the `datastar` key specifically")))
  (testing "a body method returns the stream itself, unread"
    ;; Layer 6 must not do IO: slurping here would consume a one-shot stream on
    ;; behalf of a caller that may not want it, and would put a blocking read in
    ;; a namespace whose invariant is that it has none.
    (let [body (java.io.ByteArrayInputStream. (.getBytes "{\"a\":1}" "UTF-8"))]
      (is (identical? body (wire/get-signals {:request-method :post :body body})))
      (is (= "{\"a\":1}" (slurp body)) "still unread")))
  (testing "the query param is a STRING key, which is ring's shape"
    ;; Not a keyword: this is the seam where `dj.web.http/query-params` —
    ;; ours, not ring's — has to agree with where the SDK looks. Keywordizing
    ;; would be a second convention for the same map.
    (is (nil? (wire/get-signals {:request-method :get
                                 :query-params {:datastar "{\"a\":1}"}})))))

(deftest datastar-request?-matches-the-sdk-on-every-header-value
  (testing "exact equality with \"true\" — the near misses are the point"
    (let [d (m/diffs m/datastar-request-cases
                     #(wire/datastar-request? (:request %))
                     #(sdk-api/datastar-request? (:request %)))]
      (is (empty? d) (m/report d)))))

(deftest datastar-request?-is-exact-equality-and-that-matters-twice
  (testing "written from the rule, not from either implementation"
    (is (true? (wire/datastar-request? {:headers {"datastar-request" "true"}})))
    (is (false? (wire/datastar-request? {:headers {}}))))
  (testing "our http layer lower-cases header names, so the key must be too"
    ;; `dj.web.http/request-headers` lower-cases every name (ring's shape).
    ;; Looking for `Datastar-Request` would read every action request as a page
    ;; load — silently, since a page load is a legitimate answer.
    (is (= "datastar-request" wire/datastar-request-header))
    (is (false? (wire/datastar-request? {:headers {"Datastar-Request" "true"}}))
        "which is what an already-lower-cased map means"))
  (testing "and it comma-joins a repeated header, which exact equality rejects"
    ;; A doubled header gives "true,true". `str/includes?` would have said true
    ;; here — and would also have said true for "untrue".
    (is (false? (wire/datastar-request? {:headers {"datastar-request" "true,true"}})))
    (is (false? (wire/datastar-request? {:headers {"datastar-request" "untrue"}})))
    (is (false? (wire/datastar-request? {:headers {"datastar-request" "TRUE"}})))))

