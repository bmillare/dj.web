(ns dj.web.datastar.wire-test
  "Layer 2, the **letters**: `dj.web.datastar.wire` diffed against
  `starfederation.datastar.clojure.api.elements` / `.signals` over the shared
  matrix in `dj.web.wire-matrix` (which explains the method).

  Extraction stages asserted here: **2** — `->patch-elements` and `->patch-signals` for
  the no-options case, which is everything the original namespace-browser example and `http_test` call —
  and **4**, `get-signals` and `datastar-request?` — layer 6, the two functions
  in this namespace that run on the way *in*. The JSON parse that follows
  `get-signals` is layer 4's and is asserted in `http-test/signals-in`, over a
  real socket, because its failure mode is an HTTP status rather than a value.

  the extraction design  named the reason: `String.lines()` versus `clojure.string/split-lines` on a
  lone `\\r`. That prediction is stated as its own test rather than folded into
  the differential, and it comes in two parts:

  - `the-harness-catches-the-mistake-it-was-built-to-catch` runs the naive
    implementation through the matrix as a **negative control**. the differential harness's whole
    claim is that a diff against the oracle would have caught layer 2's silent
    mistakes; a matrix whose axes happen to miss the bug passes exactly as
    quietly as a correct implementation, so the claim is worth an assertion.
  - `split-lines-would-have-been-wrong` names each divergence. Running the
    control turned up **three**, not the one the plan predicted — the extra one
    is a trailing newline, and it fires more often than the `\\r` does."
  (:require [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [dj.web.datastar.wire :as wire]
            [dj.web.wire-matrix :as m]
            [starfederation.datastar.clojure.api :as sdk-api]
            [starfederation.datastar.clojure.api.common :as sdk-common]
            [starfederation.datastar.clojure.api.elements :as sdk-elements]
            [starfederation.datastar.clojure.api.signals :as sdk-signals]
            [starfederation.datastar.clojure.consts :as sdk-consts]))

;; -----------------------------------------------------------------------------
;; Layer 1 — the Datastar literals
;; -----------------------------------------------------------------------------

(deftest datastar-literals-match-the-sdk
  (testing "every hand-written literal equals its code-generated counterpart"
    ;; Upstream's `consts.clj` says "auto-generated by Datastar. DO NOT EDIT" —
    ;; these strings are generated from the spec across every language SDK at
    ;; once, so ours are the only hand-maintained copy in the world and this is
    ;; the only thing that would tell us the spec moved.
    (is (= sdk-consts/event-type-patch-elements wire/event-type-patch-elements))
    (is (= sdk-consts/event-type-patch-signals  wire/event-type-patch-signals))
    (is (= sdk-consts/elements-dataline-literal wire/elements-dataline-literal))
    (is (= sdk-consts/signals-dataline-literal  wire/signals-dataline-literal))
    (is (= sdk-consts/datastar-key              wire/datastar-key)))
  (testing "and the option keys we reject by name"
    (is (= sdk-common/selector                 wire/selector))
    (is (= sdk-common/patch-mode               wire/patch-mode))
    (is (= sdk-common/use-view-transition      wire/use-view-transition))
    (is (= sdk-common/view-transition-selector wire/view-transition-selector))
    (is (= sdk-common/element-namespace        wire/element-namespace))
    (is (= sdk-common/only-if-missing          wire/only-if-missing))))

